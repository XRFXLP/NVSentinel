// TestRealPolicyFieldExtractionIsComplete asserts that every real policy yields
// a complete field set. An incomplete extraction is not itself a bug -- the
// caller is required to fall back to caching the object whole -- but it means
// the policy gets no memory saving, so it is worth knowing which ones do.
func TestRealPolicyFieldExtractionIsComplete(t *testing.T) {
	env, err := celenv.NewCompilerEnvironment()
	if err != nil {
		t.Fatalf("compiler environment: %v", err)
	}

	for _, p := range realPolicies {
		for _, expr := range []struct{ what, src string }{
			{"predicate", p.predicate},
			{"nodeAssociation", p.nodeAssociation},
		} {
			if expr.src == "" {
				continue
			}

			ast, err := env.Compile(expr.src)
			if err != nil {
				t.Errorf("%s/%s: compile: %v", p.name, expr.what, err)
				continue
			}

			paths, ok := celenv.ResourceFieldPaths(ast)
			if !ok {
				t.Logf("%s/%s: extraction incomplete, object must be cached whole", p.name, expr.what)
				continue
			}

			if len(paths) == 0 {
				t.Errorf("%s/%s: complete extraction returned no paths", p.name, expr.what)
			}

			t.Logf("%s/%s [%s]: %v", p.name, expr.what, p.kind, paths)
		}
	}
}

var _ = context.Background

// asPolicies converts the table into the config type derivePolicyFieldPaths takes.
func asPolicies() []config.Policy {
	out := make([]config.Policy, 0, len(realPolicies))

	for _, p := range realPolicies {
		pol := config.Policy{
			Name:      p.name,
			Enabled:   true,
			Resource:  config.ResourceSpec{Group: "", Version: "v1", Kind: p.kind},
			Predicate: config.PredicateSpec{Expression: p.predicate},
		}
		if p.nodeAssociation != "" {
			pol.NodeAssociation = &config.AssociationSpec{Expression: p.nodeAssociation}
		}

		out = append(out, pol)
	}

	return out
}

// TestRealPolicyCrossKindLookupFieldsSurvivePruning is the regression that
// matters. Three real policies are Pod policies that read fields off a Node
// through lookup(): GPUOperatorCudaValidatorMissingClique reads
// metadata.labels, SlinkySilentDrain reads metadata.annotations. Nothing in any
// Node policy reads metadata.labels, so if the lookup paths were not folded into
// the Node cache's transform, the Node would be cached without labels, the
// lookup would return an object missing them, and the predicate would evaluate
// false instead of true. That is a silent miss: no error, no log, just a GB200
// node with a missing clique that is never reported.
func TestRealPolicyCrossKindLookupFieldsSurvivePruning(t *testing.T) {
	compiler, err := celenv.NewCompilerEnvironment()
	if err != nil {
		t.Fatalf("compiler environment: %v", err)
	}

	derived := derivePolicyFieldPaths(compiler, asPolicies())

	nodeGVK := schema.GroupVersionKind{Group: "", Version: "v1", Kind: "Node"}

	node := derived.forGVK(nodeGVK)
	if node == nil {
		t.Fatal("no field paths derived for Node")
	}

	entry := node.cacheEntryFor(nodeGVK)
	if !entry.servesLookups {
		t.Fatal("Node cache does not serve lookups, so every lookup() falls back to a live API GET")
	}

	if entry.transform == nil {
		t.Skip("Node is cached whole, so nothing can be pruned away")
	}

	// Build a Node carrying exactly the fields the lookup policies read.
	obj := map[string]any{
		"apiVersion": "v1",
		"kind":       "Node",
		"metadata": map[string]any{
			"name": "node-1",
			"labels": map[string]any{
				"nvidia.com/gpu.product": "NVIDIA-GB200",
			},
			"annotations": map[string]any{
				"nodeset.slinky.slurm.net/node-cordon-reason": "drained by operator",
			},
		},
		"spec": map[string]any{"unschedulable": true},
		"status": map[string]any{
			"conditions": []any{
				map[string]any{"type": "Ready", "status": "True"},
			},
		},
	}

	u := &unstructured.Unstructured{Object: obj}

	out, err := entry.transform(u)
	if err != nil {
		t.Fatalf("transform: %v", err)
	}

	pruned, ok := out.(*unstructured.Unstructured)
	if !ok {
		t.Fatalf("transform returned %T", out)
	}

	meta, _ := pruned.Object["metadata"].(map[string]any)
	if meta == nil {
		t.Fatal("metadata pruned away entirely")
	}

	if _, ok := meta["labels"]; !ok {
		t.Error("metadata.labels pruned from the Node cache: " +
			"GPUOperatorCudaValidatorMissingClique reads it through lookup() and would silently never fire")
	}

	if _, ok := meta["annotations"]; !ok {
		t.Error("metadata.annotations pruned from the Node cache: " +
			"SlinkySilentDrain reads it through lookup() and would silently change behaviour")
	}

	if _, ok := meta["name"]; !ok {
		t.Error("metadata.name pruned: nodeAssociation reads it through lookup()")
	}

	t.Logf("Node object after pruning: %v", pruned.Object)
}

