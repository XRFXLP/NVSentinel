// TestRealPolicyEvaluationUnchangedByPruning evaluates every real policy twice,
// once against the whole object and once against the object the cache would
// actually hold, and requires the two to agree. This is the check that the
// field analysis is not merely plausible but correct: if it drops a field a
// policy reads, the pruned evaluation diverges here.
//
// Policies using lookup() are evaluated for their non-lookup behaviour only;
// the lookup path is covered by TestRealPolicyCrossKindLookupFieldsSurvivePruning.
func TestRealPolicyEvaluationUnchangedByPruning(t *testing.T) {
	compiler, err := celenv.NewCompilerEnvironment()
	if err != nil {
		t.Fatalf("compiler environment: %v", err)
	}

	derived := derivePolicyFieldPaths(compiler, asPolicies())

	fixtures := map[string]func() map[string]any{"Node": richNode, "Pod": richPod}

	var fired int

	for _, p := range realPolicies {
		t.Run(p.name+"/"+p.kind, func(t *testing.T) {
			if containsLookup(p.predicate) {
				t.Skip("uses lookup(); covered by the cross-kind test")
			}

			gvk := schema.GroupVersionKind{Group: "", Version: "v1", Kind: p.kind}

			entry := derived.forGVK(gvk).cacheEntryFor(gvk)
			if entry.transform == nil {
				t.Skip("cached whole, nothing pruned")
			}

			ast, err := compiler.Compile(p.predicate)
			if err != nil {
				t.Fatalf("compile: %v", err)
			}

			full := fixtures[p.kind]()

			u := &unstructured.Unstructured{Object: fixtures[p.kind]()}

			out, err := entry.transform(u)
			if err != nil {
				t.Fatalf("transform: %v", err)
			}

			prunedObj, _ := out.(*unstructured.Unstructured)

			gotFull, err := compiler.Evaluate(ast, full, context.Background())
			if err != nil {
				t.Fatalf("evaluate full: %v", err)
			}

			gotPruned, err := compiler.Evaluate(ast, prunedObj.Object, context.Background())
			if err != nil {
				t.Fatalf("evaluate pruned: %v", err)
			}

			if gotFull.Value() != gotPruned.Value() {
				t.Errorf("pruning changed the result: full=%v pruned=%v\nretained object: %v",
					gotFull.Value(), gotPruned.Value(), prunedObj.Object)
			}

			if v, ok := gotFull.Value().(bool); ok && v {
				fired++
			}

			t.Logf("full=%v pruned=%v", gotFull.Value(), gotPruned.Value())
		})
	}

	if fired == 0 {
		t.Error("no policy evaluated true against its fixture, so agreement proves nothing")
	}
}

func containsLookup(s string) bool {
	for i := 0; i+7 <= len(s); i++ {
		if s[i:i+7] == "lookup(" {
			return true
		}
	}

	return false
}
